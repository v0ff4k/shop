#!/bin/bash

# Настройки по умолчанию
LOG_DIR="./var/log"
KEEP_LINES=100

# Если передан первый аргумент, используем его как количество сохраняемых строк
if [ -n "$1" ]; then
    # Проверка, что аргумент является положительным числом
    if ! [[ "$1" =~ ^[0-9]+$ ]] || [ "$1" -le 0 ]; then
        echo "Ошибка: Аргумент должен быть положительным целым числом."
        exit 1
    fi
    KEEP_LINES=$1
fi

# Проверка существования директории
if [ ! -d "$LOG_DIR" ]; then
    echo "Ошибка: Директория $LOG_DIR не найдена."
    exit 1
fi

echo "Начинаю обработку логов в $LOG_DIR. Сохраняю последние $KEEP_LINES строк."
echo "Используются числовые ID владельцев для совместимости."

# Счетчик обработанных файлов
count=0
error_count=0

# Используем find для поиска всех .log файлов (не рекурсивно, только в этой папке)
# -maxdepth 1 гарантирует, что мы не залезем в подпапки
# -name "*.log" выбирает только логи
while IFS= read -r -d '' file; do
    # Пропускаем пустые файлы или очень маленькие
    filesize=$(stat -c%s "$file" 2>/dev/null || stat -f%z "$file" 2>/dev/null)

    # Если файл пустой или меньше размера одной строки (условно < 10 байт), пропускаем
    if [ "$filesize" -lt 10 ]; then
        continue
    fi

    # Создаем временный файл в той же директории (важно для mv, чтобы сохранить inode/права, если нужно)
    # Но лучше создавать во временной директории, чтобы избежать проблем с местом,
    # однако для простоты и атомарности внутри ФС создадим рядом.
    tmpfile="${file}.tmp.$$"

    # 1. Извлекаем последние N строк во временный файл
    if ! tail -n "$KEEP_LINES" "$file" > "$tmpfile"; then
        echo "Ошибка чтения $file. Пропуск."
        rm -f "$tmpfile"
        error_count=$((error_count + 1))
        continue
    fi

    # 2. Получаем права доступа (восьмеричные, например 644)
    original_perms=$(stat -c %a "$file" 2>/dev/null)

    # 3. Получаем UID и GID (числовые ID, например 1000:1000)
    # Это работает даже если пользователь удален из системы
    original_uid_gid=$(stat -c %u:%g "$file" 2>/dev/null)

    # 4. Применяем права и владельца к временному файлу
    if [ -n "$original_perms" ]; then
        chmod "$original_perms" "$tmpfile"
    fi

    if [ -n "$original_uid_gid" ]; then
        # chown понимает формат uid:gid
        if ! chown "$original_uid_gid" "$tmpfile" 2>/dev/null; then
            # Если chown не сработал (например, нет прав у текущего пользователя скрипта),
            # мы все равно попробуем сделать mv, но владелец может измениться на текущего.
            # Однако, если скрипт запущен от root, это сработает всегда.
            :
        fi
    fi

    # 5. Заменяем оригинальный файл
    if mv "$tmpfile" "$file"; then
        count=$((count + 1))
    else
        echo "Ошибка замены файла $file"
        rm -f "$tmpfile"
        error_count=$((error_count + 1))
    fi

done < <(find "$LOG_DIR" -maxdepth 1 -name "*.log" -type f -print0)

echo "Готово. Успешно обработано: $count. Ошибок: $error_count"